"""Compare Gratitude's 0.3 catalogue with the compiled BerthaML database.

Album names (YYMMDD_region-city-venue) are written into users' files, so every date
where the two disagree is listed for review before the database replaces the XML.

    python tools/compare_catalogue.py ../target/berthaml/berthaml.db ../docs/berthaml-catalogue-comparison.md
"""

import argparse
from collections import Counter, defaultdict
import gzip
import json
from pathlib import Path
import sqlite3
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent


def slug(value):
    value = value.lower().replace("&", " and ")
    for c in "'’.":
        value = value.replace(c, "")
    parts, word = [], ""
    for c in value:
        if c.isalnum():
            word += c
        elif word:
            parts.append(word)
            word = ""
    if word:
        parts.append(word)
    return "-".join(parts)


def album(date, region, city, venue):
    parts = [slug(s) for s in (region, city, venue)]
    return date[2:].replace("-", "") + "_" + "-".join(p for p in parts if p)


def old_places():
    """The 0.3 rule from catalogue.rs: state, else the state in "City, ST", else country."""
    root = ET.parse(gzip.open(ROOT / "sources/catalogue.xml.gz")).getroot()
    places = {}
    for show in root.find("shows"):
        date, venue = show.get("date"), show.get("venue", "")
        city = show.get("city", "")
        city, _, listed = city.partition(", ")
        region = next((s for s in (show.get("state", ""), listed, show.get("country", "")) if s), "")
        if venue:
            places[date] = {
                "album": album(date, region, "" if city == "Unknown" else city, venue),
                "basis": show.get("basis"),
                "venue": venue,
            }
    return places


def new_places(db):
    rows = db.execute(
        "SELECT s.id, s.date, v.place, v.city, v.name FROM shows s JOIN venues v ON v.id = s.venue ORDER BY s.date, s.id"
    ).fetchall()
    by_date = defaultdict(list)
    for sid, date, region, city, venue in rows:
        by_date[date].append((sid, album(date, region, city, venue)))
    return by_date


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("db")
    parser.add_argument("output")
    args = parser.parse_args()
    db = sqlite3.connect(f"file:{args.db}?mode=ro", uri=True)
    old, new = old_places(), new_places(db)
    exclusions = defaultdict(list)
    for line in (ROOT / "reports/event-exclusions.jsonl").read_text(encoding="utf-8").splitlines():
        row = json.loads(line)
        exclusions[row["date_label"][:10]].append(f"{row['category']}: {row['venue']}")

    same, changed, several, missing, recording_only = [], [], [], [], []
    for date, before in sorted(old.items()):
        after = new.get(date, [])
        if before["basis"] == "recording-metadata":
            recording_only.append((date, before, after))
        if not after:
            missing.append((date, before))
        elif len({a for _, a in after}) > 1:
            several.append((date, before, after))
        elif after[0][1] == before["album"]:
            same.append(date)
        else:
            changed.append((date, before["album"], after[0][1]))
    added = sorted(d for d in new if d not in old)

    kinds = Counter()
    for _, b, a in changed:
        b_parts, a_parts = b.split("_", 1)[1], a.split("_", 1)[1]
        kinds["region" if b_parts.split("-")[0] != a_parts.split("-")[0] else "venue or city"] += 1

    out = [
        "# BerthaML catalogue comparison",
        "",
        "Generated by `berthaml/tools/compare_catalogue.py` from the 0.3 catalogue (`berthaml/sources/catalogue.xml.gz`) "
        "and the compiled `berthaml.db`. Album names follow `YYMMDD_region-city-venue`.",
        "",
        "| Measure | Dates |",
        "| --- | ---: |",
        f"| Dates with a venue in the 0.3 catalogue | {len(old):,} |",
        f"| Same album name | {len(same):,} |",
        f"| Different album name | {len(changed):,} |",
        f"| Several BerthaML shows at different venues | {len(several):,} |",
        f"| Not a BerthaML show | {len(missing):,} |",
        f"| BerthaML show dates absent from the 0.3 catalogue | {len(added):,} |",
        f"| 0.3 recording-only dates | {len(recording_only):,} |",
        "",
        "With the database, an import whose date has no BerthaML show takes its place from the folder's notes, "
        "as 0.3 did for dates outside its catalogue. Where several shows share a date at different venues, "
        "the notes' venue picks one; otherwise the notes' place stands.",
        "",
        "## Different album names",
        "",
        f"Changed parts: {', '.join(f'{k} {v}' for k, v in sorted(kinds.items())) or 'none'}.",
        "",
        "| Date | 0.3 | BerthaML |",
        "| --- | --- | --- |",
    ]
    out += [f"| {d} | `{b}` | `{a}` |" for d, b, a in changed]
    out += ["", "## Several shows at different venues", "", "| Date | 0.3 | BerthaML |", "| --- | --- | --- |"]
    out += [f"| {d} | `{b['album']}` | {'<br>'.join(f'{sid}: `{a}`' for sid, a in after)} |" for d, b, after in several]
    out += [
        "",
        "## 0.3 recording-only dates",
        "",
        "Dates the 0.3 catalogue knew only from recording metadata, with no gdshowsdb performance.",
        "",
        "| Date | 0.3 venue | BerthaML | Jerrybase exclusion |",
        "| --- | --- | --- | --- |",
    ]
    for d, b, after in recording_only:
        shows = ", ".join(sid for sid, _ in after) or "none"
        out.append(f"| {d} | {b['venue']} | {shows} | {'; '.join(exclusions.get(d, [])) or ''} |")
    out += ["", "## Other dates without a BerthaML show", "", "| Date | 0.3 venue | Jerrybase exclusion |", "| --- | --- | --- |"]
    out += [
        f"| {d} | {b['venue']} | {'; '.join(exclusions.get(d, [])) or ''} |"
        for d, b in missing
        if b["basis"] != "recording-metadata"
    ]
    out += ["", "## BerthaML dates absent from 0.3", ""]
    out += [", ".join(added) or "None.", ""]
    Path(args.output).write_text("\n".join(out), encoding="utf-8")
    print(
        f"same {len(same)}, changed {len(changed)} ({dict(kinds)}), several {len(several)}, "
        f"missing {len(missing)}, recording-only {len(recording_only)}, added {len(added)}"
    )


if __name__ == "__main__":
    main()
